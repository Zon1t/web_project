SET PAGESIZE 100
SET LINESIZE 200
SET FEEDBACK OFF
COLUMN LOGIN_ID FORMAT A10
COLUMN CONTENT FORMAT A70
COLUMN STATUS FORMAT A10
COLUMN MSG_TYPE FORMAT A8

PROMPT ===== 1) P1(13) 참여자: testah, testam 2행 (둘 다 CONFIRMED_YN=N)
SELECT pm.PARTY_ID, m.LOGIN_ID, pm.CONFIRMED_YN, pm.THUMBS_UP_YN
  FROM PARTY_MEMBER pm JOIN MEMBER m ON m.MEMBER_ID = pm.MEMBER_ID
 WHERE pm.PARTY_ID = 13 ORDER BY pm.PARTY_MEMBER_ID;

PROMPT ===== 1) P1(13) 대화: 첫 행 SYSTEM '...식사팟을 만들었습니다'
SELECT CHAT_ID, MSG_TYPE, MEMBER_ID, CONTENT FROM PARTY_CHAT WHERE PARTY_ID = 13 ORDER BY CHAT_ID;

PROMPT ===== 3) P4(16), P5(17): 둘 다 DELETED, 행 수 0보다 큼
SELECT p.PARTY_ID, p.STATUS,
       (SELECT COUNT(*) FROM PARTY_MEMBER pm WHERE pm.PARTY_ID = p.PARTY_ID) AS MEMBER_ROWS,
       (SELECT COUNT(*) FROM PARTY_CHAT pc WHERE pc.PARTY_ID = p.PARTY_ID) AS CHAT_ROWS
  FROM MEAL_PARTY p WHERE p.PARTY_ID IN (16, 17) ORDER BY p.PARTY_ID;

